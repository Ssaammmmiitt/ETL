-- 03 REJECTS BY RULE: what each gate put in AUDIT.C_REJ_TABLE per day, and the money it held back.
-- The second query shows one full rejected row per rule (RAW_RECORD keeps the whole source line).
USE ROLE MEDALLION_ROLE; USE WAREHOUSE MEDALLION_WH; USE DATABASE MEDALLION_DB;
SET FROM_DT = '2026-11-10';
SET TO_DT   = '2026-11-14';

SELECT
    INGEST_DT,
    GATE_ID,
    REASON_CD,
    OBJECT_NM AS HEADED_FOR,
    COUNT(*) AS ROWS_REJECTED,
    COALESCE(SUM(TRY_TO_NUMBER(RAW_RECORD:NET_SALES_AMT::VARCHAR, 18, 2)), 0) AS NET_SALES_AMT
FROM AUDIT.C_REJ_TABLE
WHERE INGEST_DT BETWEEN $FROM_DT AND $TO_DT
GROUP BY 1, 2, 3, 4
ORDER BY 1, 2, 3;

SELECT GATE_ID, REASON_CD, INGEST_DT, SOURCE_FILE, RAW_RECORD
FROM AUDIT.C_REJ_TABLE
WHERE INGEST_DT BETWEEN $FROM_DT AND $TO_DT
QUALIFY ROW_NUMBER() OVER (PARTITION BY GATE_ID, REASON_CD ORDER BY INGEST_DT) = 1
ORDER BY GATE_ID, REASON_CD;
