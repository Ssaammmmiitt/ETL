-- 06 CONTROL TABLES (AUDIT schema). Run one statement at a time (cursor in it, Ctrl+Enter).
USE ROLE MEDALLION_ROLE; USE WAREHOUSE MEDALLION_WH; USE DATABASE MEDALLION_DB;

-- A. C_BATCH_SCRIPTS: which scripts run, in which order.
SELECT RUN_SEQ, TASK_ID, LAYER, SCRIPT_PATH, TARGET_TABLE, GATE_ID, ON_FAIL
FROM AUDIT.C_BATCH_SCRIPTS
ORDER BY RUN_SEQ;

-- B. C_PARAM: the parameters of each batch (GOLD_REWOUND_FROM appears only on a reload of a past day).
SELECT BUSINESS_DT, BATCH_ID, PARAM_NM, PARAM_VAL
FROM AUDIT.C_PARAM
ORDER BY BUSINESS_DT, BATCH_ID, PARAM_NM;

-- C. C_BATCH_LOG summary: one row per batch.
SELECT BUSINESS_DT, BATCH_ID,
       COUNT(DISTINCT TASK_ID)                         AS TASKS,
       COUNT_IF(STATUS = 'SUCCESS')                    AS SUCCESS_ROWS,
       COUNT_IF(STATUS <> 'SUCCESS')                   AS FAILED_OR_RETRY,
       DATEDIFF(second, MIN(START_TS), MAX(END_TS))    AS WALL_SEC,
       SUM(ROWS_AFFECTED)                              AS ROWS_AFFECTED
FROM AUDIT.C_BATCH_LOG
GROUP BY 1, 2
ORDER BY MIN(START_TS);

-- D. C_BATCH_LOG detail for one day (change the date): status, rows, elapsed, failure reason per task.
SELECT TASK_ID, MAP_INDEX, TRY_NUMBER, STATUS, ROWS_AFFECTED, ELAPSED_SEC, SCRIPT_PATH, FAILURE_REASON
FROM AUDIT.C_BATCH_LOG
WHERE BUSINESS_DT = '2026-11-14'
ORDER BY START_TS;

-- E. C_LOAD_DATES: last successful load date per target.
SELECT LAYER, TARGET_TABLE, LAST_LOAD_DT, LAST_RUN_DT, LAST_BATCH_ID, UPDATE_TS
FROM AUDIT.C_LOAD_DATES
ORDER BY CASE LAYER WHEN 'BRONZE' THEN 1 WHEN 'SILVER' THEN 2 WHEN 'GOLD' THEN 3 ELSE 4 END, TARGET_TABLE;

-- F. C_REJ_TABLE: rejected rows and the rule that rejected them (detail in 03_rejects_by_rule.sql).
SELECT GATE_ID, REASON_CD, COUNT(*) AS ROWS_REJECTED
FROM AUDIT.C_REJ_TABLE
GROUP BY 1, 2
ORDER BY 1, 2;
