-- 07 BUSINESS OUTPUT: the reporting view rolled up the location hierarchy to region.
USE ROLE MEDALLION_ROLE; USE WAREHOUSE MEDALLION_WH; USE DATABASE MEDALLION_DB;
SET FROM_DT = '2026-11-10';
SET TO_DT   = '2026-11-20';

SELECT
    rg.REGION_NM,
    COUNT(DISTINCT v.DAY_KY) AS DAYS,
    SUM(v.SALES_LINE_CNT)    AS LINES,
    SUM(v.SOLD_QTY)          AS SOLD_QTY,
    SUM(v.NET_SALES_AMT)     AS NET_SALES_AMT
FROM GOLD.VW_DAILY_ITEM_LOCN_SALES v
JOIN GOLD.DIM_LOCN l    ON l.LOCN_KY = v.LOCN_KY
JOIN GOLD.DIM_CITY c    ON c.CITY_KY = l.CITY_KY
JOIN GOLD.DIM_REGION rg ON rg.REGION_KY = c.REGION_KY
WHERE v.DAY_KY BETWEEN TO_NUMBER(TO_CHAR($FROM_DT::DATE, 'YYYYMMDD')) AND TO_NUMBER(TO_CHAR($TO_DT::DATE, 'YYYYMMDD'))
GROUP BY 1
ORDER BY 5 DESC;
