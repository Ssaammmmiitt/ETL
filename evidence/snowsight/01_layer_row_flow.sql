-- 01 LAYER FLOW: sales rows per day through Bronze -> Silver -> rejects -> Gold.
-- Proves nothing is lost: ROW_DIFF = 0 means every source row is either in Gold or in C_REJ_TABLE.
USE ROLE MEDALLION_ROLE; USE WAREHOUSE MEDALLION_WH; USE DATABASE MEDALLION_DB;
SET FROM_DT = '2026-11-10';
SET TO_DT   = '2026-11-20';

WITH bronze AS (
    SELECT _INGEST_DT AS DT, COUNT(*) AS BRONZE_ROWS
    FROM BRONZE.STG_SALES WHERE _INGEST_DT BETWEEN $FROM_DT AND $TO_DT GROUP BY 1
),
silver AS (
    SELECT _INGEST_DT AS DT, COUNT(*) AS SILVER_ROWS
    FROM SILVER.TMP_SALES_LINE WHERE _INGEST_DT BETWEEN $FROM_DT AND $TO_DT GROUP BY 1
),
rej AS (
    SELECT INGEST_DT AS DT,
           COUNT_IF(OBJECT_NM = 'TMP_SALES_LINE') AS REJECTED_SILVER,
           COUNT_IF(OBJECT_NM = 'FCT_SALES')      AS REJECTED_G7
    FROM AUDIT.C_REJ_TABLE WHERE INGEST_DT BETWEEN $FROM_DT AND $TO_DT GROUP BY 1
),
gold AS (
    SELECT SALE_DT AS DT, COUNT(*) AS GOLD_ROWS
    FROM GOLD.FCT_SALES WHERE SALE_DT BETWEEN $FROM_DT AND $TO_DT GROUP BY 1
)
SELECT
    b.DT,
    b.BRONZE_ROWS,
    COALESCE(s.SILVER_ROWS, 0)      AS SILVER_ROWS,
    COALESCE(r.REJECTED_SILVER, 0)  AS REJECTED_SILVER,
    COALESCE(r.REJECTED_G7, 0)      AS REJECTED_G7,
    COALESCE(g.GOLD_ROWS, 0)        AS GOLD_ROWS,
    b.BRONZE_ROWS - COALESCE(g.GOLD_ROWS, 0) - COALESCE(r.REJECTED_SILVER, 0) - COALESCE(r.REJECTED_G7, 0) AS ROW_DIFF
FROM bronze b
LEFT JOIN silver s ON s.DT = b.DT
LEFT JOIN rej r    ON r.DT = b.DT
LEFT JOIN gold g   ON g.DT = b.DT
ORDER BY b.DT;
