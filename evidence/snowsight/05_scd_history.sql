-- 05 SLOWLY CHANGING DIMENSIONS
-- SCD2: store 1008 moves city on 2026-11-13 -> two versions, the old one closed on 2026-11-12, the new one current.
-- SCD1: item 100011 description revised on 2026-11-14 -> still one row, description overwritten in place.
USE ROLE MEDALLION_ROLE; USE WAREHOUSE MEDALLION_WH; USE DATABASE MEDALLION_DB;

SELECT 'DIM_LOCN (SCD2)' AS DIMENSION, l.LOCN_ID AS NATURAL_ID, c.CITY_NM AS TRACKED_VALUE,
       l.EFFECTIVE_START_DT, l.EFFECTIVE_END_DT, l.CURRENT_FLG
FROM GOLD.DIM_LOCN l
JOIN GOLD.DIM_CITY c ON c.CITY_KY = l.CITY_KY
WHERE l.LOCN_ID = '1008'
UNION ALL
SELECT 'DIM_ITEM (SCD1)', ITEM_ID, ITEM_DESC, EFFECTIVE_START_DT, EFFECTIVE_END_DT, CURRENT_FLG
FROM GOLD.DIM_ITEM
WHERE ITEM_ID = '100011'
ORDER BY 1, 4;
